/** Safe, dependency-free project starter: staging + rename, never overwrite. */
import { existsSync, lstatSync, mkdirSync, mkdtempSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';

export type StarterLanguage = 'javascript' | 'typescript';
export interface StarterOptions { language?: StarterLanguage; dryRun?: boolean }
export interface StarterResult { directory: string; files: string[]; created: boolean }

function occupied(location: string): boolean {
  try {lstatSync(location);return true;} catch(error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') return false; throw error; }
}
function safeName(name: string): string {
  if (!/^[a-z0-9][a-z0-9._-]{0,99}$/i.test(name) || name === '.' || name === '..' || name.startsWith('.') || name.endsWith('.') || name.includes('..')) {
    throw new TypeError('Project directory name must be a simple non-hidden directory (letters, digits, underscore, dash or dot)');
  }
  return name;
}
function starterFiles(name: string, language: StarterLanguage): Record<string,string> {
  const ts = language === 'typescript';
  const packageName = name.toLowerCase().replace(/[^a-z0-9._-]/g,'-');
  const files: Record<string,string> = {
    'package.json': JSON.stringify({name:packageName,version:'0.1.0',private:true,type:'module',scripts:{dev:'zerux dev',build:'zerux build',start:'zerux start',test:'node --test tests/*.test.mjs',typecheck:ts?'tsc --noEmit':'node --check src/index.mjs'},dependencies:{zeruxjs:'*'},...(ts?{devDependencies:{typescript:'^6.0.3','@types/node':'^25.6.2'}}:{})},null,2)+'\n',
    '.gitignore': 'node_modules/\ndist/\n.env\n*.log\n',
    '.env.example': '# Add application environment variables here. Never commit secrets.\n',
    'README.md': `# ${name}\n\nGenerated by zcli. Install with \`npm install\`, run \`npm run dev\`, and test with \`npm test\`.\n\nThis starter intentionally avoids database, Redis, authentication and infrastructure requirements. For deployment, verify the published ZeruxJS version and adapters.\n`,
    'tests/smoke.test.mjs': `import test from 'node:test';\nimport assert from 'node:assert/strict';\ntest('starter source exists', () => assert.ok(true));\n`,
    [ts?'zerux.config.ts':'zerux.config.mjs']: ts
      ? `import type { ZeruxConfig } from 'zeruxjs';\nconst config: ZeruxConfig = { type: 'fix' };\nexport default config;\n`
      : `export default { type: 'fix' };\n`,
    [ts?'src/index.ts':'src/index.mjs']: `// Add routes and lifecycle plugins using the ZeruxJS public APIs.\nexport const applicationName = ${JSON.stringify(name)};\n`,
  };
  if (ts) files['tsconfig.json'] = JSON.stringify({compilerOptions:{target:'ES2022',module:'NodeNext',moduleResolution:'NodeNext',strict:true,noEmit:true,types:['node']},include:['src/**/*.ts','zerux.config.ts']},null,2)+'\n';
  return files;
}
/** Parent directory must already exist; target must not exist, including as a symlink. */
export function createZeruxProject(target: string, options: StarterOptions = {}): StarterResult {
  if (typeof target !== 'string' || !target.trim()) throw new TypeError('Project path is required');
  const directory = resolve(target);
  const name = safeName(basename(directory));
  const language = options.language ?? 'typescript';
  if (language !== 'typescript' && language !== 'javascript') throw new TypeError('Unsupported starter language');
  if (occupied(directory)) throw new Error('Project target already exists; refusing to overwrite');
  const files = starterFiles(name,language);
  const result = {directory,files:Object.keys(files).sort(),created:false};
  if (options.dryRun) return result;
  const parent = dirname(directory);
  // Directory creation is exclusive, so concurrent generators cannot replace it.
  // Contents are staged first; cleanup removes partial projects on write failures.
  const staged = mkdtempSync(join(parent,'.zerux-starter-'));
  let targetOwned = false;
  try {
    for (const [relative, body] of Object.entries(files)) {
      const file = join(staged,relative);
      mkdirSync(dirname(file),{recursive:true});
      writeFileSync(file,body,{encoding:'utf8',flag:'wx',mode:0o644});
    }
    try { mkdirSync(directory); targetOwned = true; }
    catch (error) {if ((error as NodeJS.ErrnoException).code === 'EEXIST') throw new Error('Project target appeared during generation'); throw error;}
    for (const relative of Object.keys(files)) {
      const dest = join(directory, relative);
      mkdirSync(dirname(dest),{recursive:true});
      renameSync(join(staged,relative),dest);
    }
    targetOwned = false;
    return {...result,created:true};
  } finally {
    if (targetOwned) rmSync(directory,{recursive:true,force:true});
    if (existsSync(staged)) rmSync(staged,{recursive:true,force:true});
  }
}
