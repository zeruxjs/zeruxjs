import type { SqlDialectDefinition } from '@zeruxjs/db-sql-core';
/** PostgreSQL-only SQL-core policy: numbered parameters, quoted identifiers and explicit supported RETURNING/FETCH/index guards. */
export const pgDialect: SqlDialectDefinition = {
  kind: 'pgsql',
  /** Quote a compiler-validated identifier using doubled native quote characters.
   * @param {string} identifier - Authored identifier; never a parameter value.
   * @returns {string} Native quoted identifier.
   */
  quoteIdentifier: (identifier: string) =>
    `"${identifier.replace(/"/g, '""')}"`,
  /** Emit the positional parameter marker owned by the shared compiler.
   * @param {number} index - One-based parameter position.
   * @returns {string} Native numbered placeholder.
   */
  placeholder: (index: number) => `$${index}`,
  functions: {
    LEN: 'LENGTH',
    NOW: 'NOW',
    CURRENT_TIMESTAMP: 'CURRENT_TIMESTAMP',
    CURRENT_DATE: 'CURRENT_DATE',
    DATE_DIFF: 'DATE_PART',
  },
  supportsReturning: true,
  supportsIfNotExistsIndex: true,
  supportsFetch: true,
  ilikeOperator: 'ILIKE',
  autoIncrementKeyword: 'GENERATED BY DEFAULT AS IDENTITY',
};
