import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
/** Resolve built CommonJS exports without source aliases. */
const require = createRequire(import.meta.url);
/** Public inert borrowed-executor factory. */
const { createSqlConnector } = require('../dist/index.js');
/** Explicit parameterized PostgreSQL-compatible compiler fixture. */
const dialect = {
  kind: 'postgres',
  quoteIdentifier: (s) => `"${s}"`,
  placeholder: (i) => `$${i}`,
  functions: {},
  supportsReturning: true,
  autoIncrementKeyword: 'GENERATED BY DEFAULT AS IDENTITY',
};
/** Synthetic private execution identity. */
const ctx = {
  connection: { slug: 'main', name: 'main', connector: 'pg', options: {} },
};
test('SQL compiler rejects runtime enum injection and raw CHECK clauses without reaching driver', () => {
  /** Observed prepared SQL/parameter pairs; invalid inputs must leave this empty. */
  const statements = [];
  /** Facade whose executor records only accepted native statements. */
  const conn = createSqlConnector(dialect, {
    executor: (sql, params) => {
      statements.push([sql, params]);
      return { rowCount: 1 };
    },
  });
  /** Assert compiler denial through the real public executor boundary.
   * @param {import("@zeruxjs/db").QueryOperation} op - Explicit hostile candidate from this fixture.
   * @returns {void} Fails if any unsupported input reaches native dispatch. */
  const deny = (op) => assert.throws(() => conn.execute(op, ctx));
  deny({ op: 'select', table: 'events;DROP TABLE events' });
  deny({
    op: 'select',
    table: 'events',
    orderBy: [{ by: 'id', direction: 'desc;DROP TABLE x' }],
  });
  deny({
    op: 'select',
    table: 'events',
    where: { field: 'id', operator: 'eq OR TRUE --', value: 1 },
  });
  deny({
    op: 'select',
    table: 'events',
    columns: [
      {
        expr: {
          kind: 'function',
          name: 'COUNT); DROP TABLE users;--',
          args: [],
        },
      },
    ],
  });
  deny({
    op: 'select',
    table: 'events',
    joins: [
      {
        type: 'inner; DROP TABLE users;--',
        table: 'users',
        on: { field: 'id', operator: 'eq', value: 1 },
      },
    ],
  });
  deny({ op: 'select', table: 'events', limit: '10;DROP TABLE users' });
  deny({
    op: 'createTable',
    table: 'safe',
    columns: [
      { name: 'id', type: 'integer', check: '1=1); DROP TABLE users;--' },
    ],
  });
  deny({
    op: 'createTable',
    table: 'safe',
    columns: [
      { name: 'score', type: 'decimal', precision: '20);DROP TABLE users;--' },
    ],
  });
  deny({
    op: 'createIndex',
    table: 'safe',
    name: 'ix',
    columns: ['id'],
    using: 'btree;DROP TABLE users;--',
  });
  deny({ op: 'insert', table: 'safe', values: [{ id: 1 }, { name: 'bad' }] });
  deny({ op: 'update', table: 'safe', values: {} });
  deny({ op: 'select', table: 'safe', where: { and: [] } });
  deny({
    op: 'select',
    table: 'safe',
    where: { field: 'id', operator: 'in', values: [] },
  });
  assert.equal(statements.length, 0);
});
test('parameters remain bound and pg affected counts drive CAS decisions', async () => {
  /** Observed prepared SQL/parameter pairs; invalid inputs must leave this empty. */
  const statements = [];
  /** Independent facade preserving native affected counts, including zero. */
  const c = createSqlConnector(dialect, {
    executor: (sql, params) => {
      statements.push([sql, params]);
      return { rowCount: sql.startsWith('UPDATE') ? 0 : 1, rows: [] };
    },
  });
  /** Hostile text which must remain one parameter, never SQL syntax. */
  const value = "x');DROP TABLE people;--";
  /** Native insertion count used to prove actual operation semantics. */
  const ins = await c.execute(
    { op: 'insert', table: 'people', values: { name: value } },
    ctx
  );
  assert.equal(ins.affectedCount, 1);
  assert.equal(statements[0][1][0], value);
  assert.equal(statements[0][0].includes(value), false);
  /** Zero-row CAS miss which must not become a positive count. */
  const updated = await c.execute(
    {
      op: 'update',
      table: 'people',
      values: { name: 'changed' },
      where: { field: 'id', operator: 'eq', value: 2 },
    },
    ctx
  );
  assert.equal(updated.affectedCount, 0);
});
