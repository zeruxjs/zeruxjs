import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {createSqlConnector}=require('../dist/index.js');
const dialect={kind:'postgres',quoteIdentifier:s=>`"${s}"`,placeholder:i=>`$${i}`,functions:{},supportsReturning:true,autoIncrementKeyword:'GENERATED BY DEFAULT AS IDENTITY'};
const ctx={connection:{slug:'main',name:'main',connector:'pg',options:{}}};
test('SQL compiler rejects runtime enum injection and raw CHECK clauses without reaching driver',()=>{
 const statements=[];
 const conn=createSqlConnector(dialect,{executor:(sql,params)=>{statements.push([sql,params]);return {rowCount:1};}});
 const deny=op=>assert.throws(()=>conn.execute(op,ctx));
 deny({op:'select',table:'events;DROP TABLE events'});
 deny({op:'select',table:'events',orderBy:[{by:'id',direction:'desc;DROP TABLE x'}]});
 deny({op:'select',table:'events',where:{field:'id',operator:'eq OR TRUE --',value:1}});
 deny({op:'select',table:'events',columns:[{expr:{kind:'function',name:'COUNT); DROP TABLE users;--',args:[]}}]});
 deny({op:'select',table:'events',joins:[{type:'inner; DROP TABLE users;--',table:'users',on:{field:'id',operator:'eq',value:1}}]});
 deny({op:'select',table:'events',limit:'10;DROP TABLE users'});
 deny({op:'createTable',table:'safe',columns:[{name:'id',type:'integer',check:'1=1); DROP TABLE users;--'}]});
 deny({op:'createTable',table:'safe',columns:[{name:'score',type:'decimal',precision:'20);DROP TABLE users;--'}]});
 deny({op:'createIndex',table:'safe',name:'ix',columns:['id'],using:'btree;DROP TABLE users;--'});
 deny({op:'insert',table:'safe',values:[{id:1},{name:'bad'}]});
 deny({op:'update',table:'safe',values:{}});
 deny({op:'select',table:'safe',where:{and:[]}});
 deny({op:'select',table:'safe',where:{field:'id',operator:'in',values:[]}});
 assert.equal(statements.length,0);
});
test('parameters remain bound and pg affected counts drive CAS decisions',async()=>{
 const statements=[];
 const c=createSqlConnector(dialect,{executor:(sql,params)=>{statements.push([sql,params]);return {rowCount:sql.startsWith('UPDATE')?0:1,rows:[]};}});
 const value="x');DROP TABLE people;--";
 const ins=await c.execute({op:'insert',table:'people',values:{name:value}},ctx);
 assert.equal(ins.affectedCount,1);
 assert.equal(statements[0][1][0],value);
 assert.equal(statements[0][0].includes(value),false);
 const updated=await c.execute({op:'update',table:'people',values:{name:'changed'},where:{field:'id',operator:'eq',value:2}},ctx);
 assert.equal(updated.affectedCount,0);
});
