test('direct compiler rejects unsafe shapes, enums, unknown clauses and resource excess', () => {
  /** Explicit malformed grammar/feature cases that must reject before execution. */
  const invalid = [
    { ...select, limit: null },
    { ...select, offset: null },
    { ...select, columns: [{ expr: { kind: 'value' } }] },
    { ...select, upsert: true },
    { ...select, columns: ['x; DROP TABLE items'] },
    { ...select, orderBy: [{ by: 'id', direction: '' }] },
    {
      ...select,
      joins: [
        {
          type: 'cross',
          table: 'a',
          on: { field: 'id', operator: 'eq', value: 1 },
        },
      ],
    },
    { ...select, columns: [{ expr: { kind: 'raw', sql: 'TRUE' } }] },
    {
      ...select,
      columns: [{ expr: { kind: 'function', name: 'COUNT', args: [] } }],
    },
    { ...select, where: { field: 'id', operator: 'isNull', value: 'ignored' } },
    { ...select, limit: 1, top: 2 },
    { ...select, fetch: {} },
    { ...select, as: 'bad.alias' },
    { op: 'insert', table: 'items', values: [{ id: 1 }, { id: 2, extra: 1 }] },
    {
      op: 'createTable',
      table: 'items',
      columns: [{ name: 'id', type: 'integer', check: '1=1' }],
    },
  ];
  // Prove each hostile/unknown grammar case rejects through direct public compilation.
  for (const input of invalid) {
    assert.throws(() => compileSql(pg, input));
  }
  /** Cyclic operation candidate rejected by the own-data snapshot. */
  const cyclic = { ...select };
  cyclic.where = cyclic;
  assert.throws(() => compileSql(pg, cyclic));
  assert.throws(
    () =>
      compileSql(pg, {
        ...select,
        get limit() {
          throw Error('accessor executed');
        },
      }),
    (error) => !error.message.includes('accessor executed')
  );
  /** Safe leaf wrapped into an intentionally excessive Boolean depth. */
  const deep = { field: 'id', operator: 'eq', value: 1 };
  let where = deep;
  // Construct a deliberate excessive Boolean depth without executing its contents.
  for (let i = 0; i < 40; i++) {
    where = { not: where };
  }
  assert.throws(() => compileSql(pg, { ...select, where }));
});
test('NULL and empty membership are explicit; nested/keyset placeholders stay lexical', () => {
  assert.match(
    compileSql(pg, {
      ...select,
      where: { field: 'id', operator: 'eq', value: null },
    }).statements[0],
    /IS NULL/
  );
  assert.match(
    compileSql(pg, {
      ...select,
      where: { field: 'id', operator: 'ne', value: null },
    }).statements[0],
    /IS NOT NULL/
  );
  // Verify both empty membership operators fail explicitly.
  for (const operator of ['in', 'notIn']) {
    assert.throws(() =>
      compileSql(pg, {
        ...select,
        where: { field: 'id', operator, values: [] },
      })
    );
  }
  /** Mixed-direction keyset ordering with a final unique tie-breaker. */
  const order = [
    { column: 'created', direction: 'desc' },
    { column: 'id', direction: 'asc' },
  ];
  /** Initial bounded keyset page. */
  const first = createKeysetPage({
    table: 'items',
    order,
    uniqueKey: 'id',
    limit: 2,
  });
  /** Following keyset with tenant filter and nested subquery placeholders. */
  const page = createKeysetPage({
    table: 'items',
    order,
    uniqueKey: 'id',
    limit: 2,
    after: first.continuation({ created: 7, id: 9 }),
    where: { field: 'tenant_id', operator: 'eq', value: 'private' },
  });
  page.operation.columns = [
    { expr: { kind: 'value', value: 'projection' }, as: 'label' },
  ];
  page.operation.where = {
    and: [
      page.operation.where,
      {
        operator: 'exists',
        query: {
          op: 'select',
          table: 'other',
          where: { field: 'flag', operator: 'eq', value: true },
        },
      },
    ],
  };
  /** Complete SQL/parameter pairs checked for lexical values and DDL literal behavior. */
  const compiled = compileSql(pg, page.operation);
  assert.deepEqual(compiled.params[0], [
    'projection',
    'private',
    7,
    7,
    9,
    true,
  ]);
  assert.deepEqual(compiled.statements[0].match(/\$\d+/g), [
    '$1',
    '$2',
    '$3',
    '$4',
    '$5',
    '$6',
  ]);
  /** Generated supported quantified-subquery statement. */
  const any = compileSql(pg, {
    ...select,
    where: {
      field: 'id',
      operator: 'any',
      query: { op: 'select', table: 'other', columns: ['id'] },
    },
  });
  assert.match(any.statements[0], /= ANY \(SELECT/);
});
test('unsupported dialect clauses fail before executor; FETCH ties is not silently downgraded', () => {
  /** Explicit malformed grammar/feature cases that must reject before execution. */
  const invalid = [
    [
      mysql,
      {
        op: 'createIndex',
        table: 'items',
        name: 'ix',
        columns: ['id'],
        ifNotExists: true,
      },
    ],
    [mysql, { ...select, orderBy: [{ by: 'id', nulls: 'first' }] }],
    [sqlite, { ...select, offset: 2 }],
    [
      mysql,
      { op: 'insert', table: 'items', values: { id: 1 }, returning: ['id'] },
    ],
    [pg, { op: 'switchDB', name: 'other' }],
    [
      pg,
      {
        op: 'alterTable',
        table: 'items',
        actions: [
          { type: 'modifyColumn', column: { name: 'id', type: 'integer' } },
        ],
      },
    ],
    [
      sqlite,
      { ...select, fetch: { count: 1, withTies: true }, orderBy: ['id'] },
    ],
    [
      { ...pg, supportsDdl: false },
      { op: 'dropTable', table: 'items' },
    ],
    [
      { ...pg, supportsGeneratedKeys: false },
      {
        op: 'createTable',
        table: 'items',
        columns: [{ name: 'id', type: 'integer', autoIncrement: true }],
      },
    ],
  ];
  // Verify unsupported dialect semantics reject before any executor call.
  for (const [dialect, operation] of invalid) {
    let called = false;
    /** Inert borrowed-executor facade; never owns a native transport. */
    const conn = createSqlConnector(dialect, {
      executor() {
        called = true;
      },
    });
    assert.throws(() => conn.execute(operation, context));
    assert.equal(called, false);
  }
  /** Generated ordered FETCH WITH TIES statement; semantics cannot be downgraded. */
  const fetch = compileSql(pg, {
    ...select,
    fetch: { count: 2, withTies: true },
    orderBy: ['id'],
  });
  assert.match(fetch.statements[0], /FETCH NEXT 2 ROWS WITH TIES$/);
  assert.equal(fetch.statements[0].includes('ONLY WITH'), false);
});
test('structured CHECK/index expressions are validated literals, never lost parameters', () => {
  /** Complete SQL/parameter pairs checked for lexical values and DDL literal behavior. */
  const compiled = compileSql(sqlite, {
    op: 'createTable',
    table: 'items',
    columns: [
      {
        name: 'id',
        type: 'integer',
        check: { field: 'id', operator: 'gte', value: 0 },
      },
    ],
  });
  assert.match(compiled.statements[0], /CHECK \("id" >= 0\)/);
  assert.deepEqual(compiled.params, [[]]);
  /** Generated structured index expression with inline validated DDL literals. */
  const index = compileSql(pg, {
    op: 'createIndex',
    table: 'items',
    name: 'ix',
    columns: [
      {
        kind: 'binary',
        operator: 'add',
        left: { kind: 'column', name: 'id' },
        right: 1,
      },
    ],
  });
  assert.match(index.statements[0], /"id" \+ 1/);
  assert.deepEqual(index.params, [[]]);
  assert.throws(() =>
    compileSql(mysql, {
      op: 'createTable',
      table: 'items',
      columns: [
        { name: 'name', type: 'text', default: "\\'); DROP TABLE items; --" },
      ],
    })
  );
});
test('executor failure remains actionable and compiler does not own injected clients', async () => {
  /** Synthetic original executor failure retained privately without retry. */
  const failure = Error('database offline');
  /** Inert borrowed-executor facade; never owns a native transport. */
  const conn = createSqlConnector(pg, {
    executor() {
      return Promise.reject(failure);
    },
  });
  await assert.rejects(
    conn.execute(select, context),
    (error) => error === failure
  );
  assert.equal(conn.disconnect, undefined);
  /** Facade with no configured executor; execution must fail explicitly. */
  const missing = createSqlConnector(pg, {});
  assert.throws(
    () => missing.execute(select, context),
    (error) => error.details?.code === 'MISSING_EXECUTOR'
  );
});
