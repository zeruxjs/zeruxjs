test('disposable native SQLite exercises CHECK, RETURNING, keysets and truncate cleanup', async (t) => {
  let DatabaseSync;
  try {
    ({ DatabaseSync } = await import('node:sqlite'));
  } catch {
    t.skip('node:sqlite unavailable');
    return;
  }
  /** Owned disposable in-memory node:sqlite handle, closed in finally. */
  const db = new DatabaseSync(':memory:');
  /** Inert borrowed-executor facade; never owns a native transport. */
  const conn = createSqlConnector(sqlite, {
    executor(sql, params) {
      /** Prepared native SQLite statement with values bound separately. */
      const statement = db.prepare(sql);
      return /^(?:SELECT|WITH)\b|\bRETURNING\b/.test(sql)
        ? statement.all(...params)
        : statement.run(...params);
    },
  });
  try {
    await conn.execute(
      {
        op: 'createTable',
        table: 'items',
        columns: [
          { name: 'id', type: 'integer', primary: true, autoIncrement: true },
          {
            name: 'amount',
            type: 'integer',
            check: { field: 'amount', operator: 'gte', value: 0 },
          },
          { name: 'label', type: 'text', default: "a'b" },
        ],
      },
      context
    );
    /** Actual local SQLite RETURNING records, not fabricated insert IDs. */
    const inserted = await conn.execute(
      {
        op: 'insert',
        table: 'items',
        values: [{ amount: 4 }, { amount: 4 }],
        returning: ['id', 'amount', 'label'],
      },
      context
    );
    assert.equal(inserted.rows.length, 2);
    assert.equal(inserted.rows[0].label, "a'b");
    assert.throws(
      () =>
        conn.execute(
          { op: 'insert', table: 'items', values: { amount: -1 } },
          context
        ),
      /CHECK/
    );
    /** Bounded stable scalar keyset options. */
    const args = {
      table: 'items',
      order: [
        { column: 'amount', direction: 'asc' },
        { column: 'id', direction: 'asc' },
      ],
      uniqueKey: 'id',
      limit: 1,
    };
    /** Initial bounded keyset page. */
    const first = createKeysetPage(args);
    /** Native first-page row used to create its source-bound continuation. */
    const row = (await conn.execute(first.operation, context)).rows[0];
    /** Following keyset page preserving exact column ordering. */
    const second = createKeysetPage({
      ...args,
      after: first.continuation(row),
    });
    assert.equal((await conn.execute(second.operation, context)).rows[0].id, 2);
    /** Actual SQLite DELETE-compatible truncate count. */
    const deleted = await conn.execute(
      { op: 'turcunateTable', table: 'items' },
      context
    );
    assert.equal(deleted.affectedCount, 2);
    assert.equal((await conn.execute(select, context)).rows.length, 0);
  } finally {
    db.close();
  }
});
test('dialect snapshot cannot widen capabilities through later mutation', () => {
  /** Mutable host dialect object used to prove the factory snapshots metadata. */
  const dialect = { ...mysql };
  let calls = 0;
  /** Inert borrowed-executor facade; never owns a native transport. */
  const conn = createSqlConnector(dialect, {
    executor() {
      calls++;
      return { affectedRows: 1 };
    },
  });
  dialect.supportsReturning = true;
  assert.equal(conn.capabilities.returning, 'unsupported');
  assert.throws(() =>
    conn.execute(
      { op: 'insert', table: 'items', values: { id: 1 }, returning: ['id'] },
      context
    )
  );
  assert.equal(calls, 0);
  assert.throws(
    () =>
      compileSql(mysql, {
        op: 'insert',
        table: 'items',
        values: { id: 1 },
        onConflict: { action: 'ignore' },
      }),
    (error) => error.details?.code === 'UNSUPPORTED_UPSERT'
  );
  assert.throws(() =>
    compileSql({ ...pg, ilikeOperator: 'ILIKE;SELECT 1' }, select)
  );
});
test('multi-row ordering, aggregate aliases and literal JSON values remain explicit', () => {
  /** Hostile literal text or unsafe native numeric ID fixture. */
  const unsafe = "x'); DROP TABLE items; --";
  /** Actual local SQLite RETURNING records, not fabricated insert IDs. */
  const inserted = compileSql(pg, {
    op: 'insert',
    table: 'items',
    values: [
      { id: 1, label: unsafe },
      { label: 'safe', id: 2 },
    ],
  });
  assert.deepEqual(inserted.params[0], [1, unsafe, 2, 'safe']);
  assert.equal(inserted.statements[0].includes(unsafe), false);
  /** Generated validated aggregate alias statement. */
  const count = compileSql(pg, {
    ...select,
    columns: [
      { expr: { kind: 'function', name: 'COUNT', args: ['*'] }, as: 'total' },
    ],
  });
  assert.match(count.statements[0], /COUNT\(\*\) AS "total"/);
  /** Business JSON object whose kind field must remain literal data. */
  const literal = { kind: 'business-data', text: unsafe };
  /** Compiled literal JSON expression; no raw AST passthrough. */
  const json = compileSql(pg, {
    ...select,
    columns: [{ expr: { kind: 'value', value: literal }, as: 'payload' }],
  });
  assert.deepEqual(json.params[0], [literal]);
  assert.match(
    compileSql(sqlite, { ...select, limit: 0 }).statements[0],
    /LIMIT 0$/
  );
});
