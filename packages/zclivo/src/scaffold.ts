/** Compatible minimal template over the shared bounded generator engine. */
import { basename, resolve } from 'node:path';
import {
  createProjectGenerator,
  writeProjectPlan,
  type ProjectTemplate,
  type ProjectLanguage,
  type ProjectWriteResult,
  type ResolvedProjectOptions,
} from './generator.js';
export type StarterLanguage = ProjectLanguage;
export interface StarterOptions {
  language?: StarterLanguage;
  dryRun?: boolean;
  name?: string;
  port?: number;
  renderer?: string;
  mode?: string;
  signal?: AbortSignal;
}
export type StarterResult = ProjectWriteResult;
export const starterRuntimeVersions = Object.freeze({
  node: '>=24.15.0',
  zeruxjs: '0.0.4',
  typescript: '^5.9.3',
  nodeTypes: '^25.4.0',
});
export const zeruxMinimalTemplate: ProjectTemplate = Object.freeze({
  id: 'zerux-minimal',
  capabilities: Object.freeze([
    {
      mode: 'minimal',
      renderer: 'none',
      languages: Object.freeze(['typescript', 'javascript'] as const),
    },
  ]),
  render(options: Readonly<ResolvedProjectOptions>) {
    const ts = options.language === 'typescript',
      name = options.name;
    const config = {
      type: 'fix',
      server: { port: options.port, devPort: options.port },
    };
    const files: Record<string, string> = {
      'package.json':
        JSON.stringify(
          {
            name: options.packageName,
            version: '0.1.0',
            private: true,
            type: 'module',
            engines: { node: starterRuntimeVersions.node },
            scripts: {
              dev: 'zerux dev',
              build: 'zerux build',
              start: 'zerux start',
              test: 'node --test tests/*.test.mjs',
              typecheck: ts ? 'tsc --noEmit' : 'node --check src/index.mjs',
            },
            dependencies: { zeruxjs: starterRuntimeVersions.zeruxjs },
            ...(ts
              ? {
                  devDependencies: {
                    typescript: starterRuntimeVersions.typescript,
                    '@types/node': starterRuntimeVersions.nodeTypes,
                  },
                }
              : {}),
          },
          null,
          2,
        ) + '\n',
      '.gitignore': 'node_modules/\ndist/\n.zerux/\n.env\n*.log\n',
      '.env.example':
        '# Add application environment variables here. Never commit secrets.\n',
      'README.md': `# ${name}\n\nGenerated by zclivo (minimal mode; no renderer runtime). Requires Node ${starterRuntimeVersions.node}.\n\nInstall explicitly with \`npm install\`, then choose \`npm run dev\`, \`npm run build\` or \`npm test\`. None were run by the generator. Port: ${options.port}.\n\nNo database, Redis, auth, infrastructure or browser integration is configured. Verify release availability and deployment requirements separately.\n`,
      'tests/smoke.test.mjs': `import test from 'node:test';\nimport assert from 'node:assert/strict';\nimport {existsSync} from 'node:fs';\ntest('starter source exists',()=>assert.ok(existsSync(new URL('../src/${ts ? 'index.ts' : 'index.mjs'}',import.meta.url))));\n`,
      [ts ? 'zerux.config.ts' : 'zerux.config.mjs']: ts
        ? `import type {ZeruxConfig} from 'zeruxjs';\nconst config:ZeruxConfig=${JSON.stringify(config, null, 2)};\nexport default config;\n`
        : `export default ${JSON.stringify(config, null, 2)};\n`,
      [ts ? 'src/index.ts' : 'src/index.mjs']:
        `// Add routes and lifecycle plugins using the ZeruxJS public APIs.\nexport const applicationName = ${JSON.stringify(name)};\n`,
    };
    if (ts)
      files['tsconfig.json'] =
        JSON.stringify(
          {
            compilerOptions: {
              target: 'ES2022',
              module: 'NodeNext',
              moduleResolution: 'NodeNext',
              strict: true,
              noEmit: true,
              types: ['node'],
            },
            include: ['src/**/*.ts', 'zerux.config.ts'],
          },
          null,
          2,
        ) + '\n';
    return files;
  },
});
export const minimalProjectGenerator = createProjectGenerator([
  zeruxMinimalTemplate,
]);
/** Parent exists; target never exists, including dangling symlinks. Does not install/run anything. */
export function createZeruxProject(
  target: string,
  options: StarterOptions = {},
): StarterResult {
  if (typeof target !== 'string' || !target.trim())
    throw new TypeError('Project path is required');
  if (
    !options ||
    typeof options !== 'object' ||
    Array.isArray(options) ||
    Object.keys(options).some(
      (k) =>
        ![
          'language',
          'dryRun',
          'name',
          'port',
          'renderer',
          'mode',
          'signal',
        ].includes(k),
    ) ||
    (options.dryRun !== undefined && typeof options.dryRun !== 'boolean')
  )
    throw new TypeError('Invalid starter options');
  const plan = minimalProjectGenerator.plan({
    destination: target,
    name: options.name ?? basename(resolve(target)),
    language: options.language,
    port: options.port,
    renderer: options.renderer,
    mode: options.mode,
  });
  if (options.dryRun) {
    options.signal?.throwIfAborted();
    return {
      directory: plan.options.destination,
      files: Object.keys(plan.files),
      created: false,
    };
  }
  return writeProjectPlan(plan, { signal: options.signal });
}
